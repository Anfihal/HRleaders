"""Vendor-neutral ports. Demo adapters implement the same contracts as real providers."""

from typing import Any, Protocol
from uuid import UUID

from app.recruiting.domain import Interview


class RecruitingRepository(Protocol):
    def list(self, kind: str, owner_id: UUID) -> list[dict[str, Any]]: ...
    def get(self, kind: str, entity_id: UUID, owner_id: UUID) -> dict[str, Any]: ...
    def save(
        self, kind: str, entity_id: UUID, owner_id: UUID, data: dict[str, Any]
    ) -> dict[str, Any]: ...


class LLMProvider(Protocol):
    def next_question(self, session: Interview, answer: str) -> str: ...
    def evaluate(
        self, session: Interview, *, context: dict[str, Any] | None = None
    ) -> dict[str, Any]: ...


class VoiceProvider(Protocol):
    def capabilities(self) -> dict[str, Any]: ...


class AvatarProvider(Protocol):
    def generate(self, source: bytes, options: dict[str, Any]) -> dict[str, Any]: ...


class VideoProvider(Protocol):
    def prepare(self, options: dict[str, Any]) -> dict[str, Any]: ...


class RecruitingDirectory(Protocol):
    def context(self, owner_id: UUID, vacancy_id: UUID, candidate_id: UUID) -> dict[str, Any]: ...
    def participant_owner(self, interview_id: UUID, user_id: UUID) -> UUID: ...
    def link(
        self, interview_id: UUID, vacancy_id: UUID, candidate_id: UUID, scenario_id: UUID
    ) -> None: ...
    def image(self, avatar_id: UUID) -> bytes: ...
    def save_image(self, avatar_id: UUID, content: bytes) -> None: ...
    def delete_image(self, avatar_id: UUID) -> None: ...


class StorageProvider(Protocol):
    def put(self, key: str, content: bytes) -> None: ...
    def get(self, key: str) -> bytes: ...
    def delete(self, key: str) -> None: ...


class WorkflowJournal(Protocol):
    def enqueue(self, kind: str, entity_id: UUID, owner_id: UUID, max_attempts: int) -> UUID: ...
    def retry(self, job_id: UUID, owner_id: UUID) -> None: ...
    def emit(
        self,
        subject: str,
        entity_id: UUID,
        owner_id: UUID,
        payload: dict[str, Any],
        job_id: UUID | None = None,
    ) -> None: ...


class MessageTransport(Protocol):
    async def publish(self, subject: str, envelope: dict[str, Any]) -> None: ...
