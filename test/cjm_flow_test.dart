import 'package:flutter/widgets.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:shadcn_flutter/shadcn_flutter.dart' as s;
import 'package:hrleaders/app.dart';
import 'package:hrleaders/core/di/app_dependencies.dart';
import 'package:hrleaders/core/domain/value_objects.dart';
import 'package:hrleaders/core/theme/preferences_bloc.dart';
import 'package:hrleaders/features/candidates/presentation/profile_page.dart';

Future<void> _pumpSettled(WidgetTester tester) async {
  for (var i = 0; i < 8; i++) {
    await tester.pump();
    await tester.pump(const Duration(milliseconds: 250));
  }
}

void main() {
  testWidgets('candidate completes a test and opens its measured report', (
    tester,
  ) async {
    tester.view.physicalSize = const Size(1440, 1000);
    tester.view.devicePixelRatio = 1;
    addTearDown(tester.view.resetPhysicalSize);
    addTearDown(tester.view.resetDevicePixelRatio);

    final dependencies = AppDependencies.demo();
    await dependencies.auth.login(
      Email('candidate@demo.hrleaders.example'),
      'Demo12345',
    );
    await tester.pumpWidget(
      HrleadersApp(
        dependencies: dependencies,
        preferences: PreferencesBloc(
          initial: AppPreferences(
            locale: const Locale('en'),
            theme: s.ThemeMode.light,
          ),
        ),
        initialLocation: '/candidate/profile',
      ),
    );
    await _pumpSettled(tester);
    expect(find.byType(ProfilePage), findsOneWidget);
    await tester.ensureVisible(find.text('Open test catalog'));
    await tester.tap(find.text('Open test catalog'));
    await _pumpSettled(tester);
    await tester.tap(find.text('Start test'));
    await _pumpSettled(tester);

    for (final answer in ['Hash map', '4', 'Sorted data']) {
      await tester.tap(find.text(answer));
      await _pumpSettled(tester);
    }
    await tester.tap(find.text('Finish test'));
    await _pumpSettled(tester);

    expect(find.text('100%'), findsOneWidget);
    expect(find.text('3/3'), findsOneWidget);
    expect(find.text('Demonstrated strengths'), findsOneWidget);
    expect(tester.takeException(), isNull);
    await tester.pumpWidget(const SizedBox());
  });

  testWidgets('HR demo assistant responds with a marked hiring template', (
    tester,
  ) async {
    tester.view.physicalSize = const Size(1280, 900);
    tester.view.devicePixelRatio = 1;
    addTearDown(tester.view.resetPhysicalSize);
    addTearDown(tester.view.resetDevicePixelRatio);

    final dependencies = AppDependencies.demo();
    await dependencies.auth.login(
      Email('hr@demo.hrleaders.example'),
      'Demo12345',
    );
    await tester.pumpWidget(
      HrleadersApp(
        dependencies: dependencies,
        preferences: PreferencesBloc(
          initial: AppPreferences(
            locale: const Locale('en'),
            theme: s.ThemeMode.dark,
          ),
        ),
        initialLocation: '/employer',
      ),
    );
    await _pumpSettled(tester);
    await tester.tap(find.text('HR AI Assistant'));
    await _pumpSettled(tester);
    await tester.tap(find.text('Interview questions'));
    await _pumpSettled(tester);

    expect(
      find.text(
        'Demonstration assistant. Replies are local templates, not generated by a live AI service. Do not enter candidate personal data.',
      ),
      findsOneWidget,
    );
    expect(find.text('Demo'), findsOneWidget);
    expect(find.textContaining('personal contribution'), findsOneWidget);
    expect(tester.takeException(), isNull);
    await tester.pumpWidget(const SizedBox());
  });
}
